const points = (flat: readonly number[]): Vector2[] => {
  const out: Vector2[] = [];
  for (let i = 0; i < flat.length; i += 2) out.push(new Vector2(flat[i], flat[i + 1]));
  return out;
};

/**
 * One pictogram as three.js shapes, ready to extrude. Outlines wind counter-
 * clockwise and holes clockwise, the way the model's own artwork does.
 */
export function crateIconShapes(kind: CrateIconKind): Shape[] {
  return ICONS[kind].map((part) => {
    const shape = new Shape(points(part.outline));
    for (const hole of part.holes ?? []) shape.holes.push(new Path(points(hole)));
    return shape;
  });
}
