// The four file pictograms the hero's crates carry, lifted out of the
// authoring model
// `.claude/Киберпанк пилоны_ четыре варианта/icon-crate-audio.glb`.
//
// The model draws them as extruded outline artwork - a rounded frame with a
// mountain and a sun for an image, a camera body with its lens, a music note,
// a page with text lines - and there is no way to reach that silhouette from
// primitives. So the contours themselves are the port: each array below is one
// closed loop of the shape the model extruded, flattened to `x, y, x, y, ...`
// in model units, where every glyph fits a 0.412-unit square centred on the
// origin. Douglas-Peucker at a 0.0012 tolerance took some 1500 sampled points
// down to 420, which is three thousandths of the glyph - far under a pixel at
// any size the hero draws a crate.
//
// Regenerating: read each `icon_*` node's mesh out of the GLB and take the
// boundary of its flat end cap - the edges its triangulation uses once, walked
// into loops. The cap, not the middle of the extrusion: three.js puts the end
// caps on the shape's own outline and bulges the middle out by `bevelSize`, so
// the cap is the shape and the widest ring is 0.0035 too fat everywhere.
// Nest the loops by containment (a loop inside a hole is a shape again - the
// mountain and the sun sit inside the frame's hole), and wind outlines
// counter-clockwise, holes clockwise.
